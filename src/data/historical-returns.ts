/**
 * Gets historical returns data filtered by starting year and duration.
 */
export function getHistoricalDataForPeriod(
  startYear: number,
  startMonth: number,
  durationMonths: number
): HistoricalReturn[] {
  const result: HistoricalReturn[] = [];
  let monthIndex = 0;

  for (const data of historicalReturns) {
    if (
      data.year > startYear ||
      (data.year === startYear && data.month >= startMonth)
    ) {
      if (monthIndex >= durationMonths) break;
      result.push(data);
      monthIndex++;
    }
  }

  return result;
}

/**
 * Gets all available start years from the dataset.
 */
export function getAvailableStartYears(): number[] {
  const years = new Set(historicalReturns.map((r) => r.year));
  return Array.from(years).sort();
}

/**
 * Gets historical data starting from a specific month/year.
 */
export function getHistoricalStartingFrom(
  startYear: number,
  startMonth: number
): HistoricalReturn[] {
  return historicalReturns.filter(
    (r) =>
      r.year > startYear || (r.year === startYear && r.month >= startMonth)
  );
}
